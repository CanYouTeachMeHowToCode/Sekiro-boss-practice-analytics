"""A local page for reviewing the version-2 action → move table row by row (standard library only, 127.0.0.1).

Usage: python -I v2_review.py [port]          (default 8771; then open http://127.0.0.1:<port> in a browser)

Shows every animation of semantic/genichiro_v2_actions.csv: what a hit by it counts as now, what version 2 proposes
and why, with the owner's labels and how often it was recorded. The owner marks each row ✅ 通过 or ❌ 不通过 and can
write a reason; each mark is saved at once to semantic/genichiro_v2_review.csv (key, mark, reason, updated) and the
table (.csv and .md) is regenerated by v2_actions.py, so the .md always shows the marks. The proposed English names
(v2_actions.NAME_REVIEWS) are confirmed the same way. The unchanged rows, all ordinary attacks that keep their move,
can be approved together; that asks first.
"""

