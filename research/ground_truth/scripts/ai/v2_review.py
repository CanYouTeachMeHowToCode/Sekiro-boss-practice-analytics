class Handler(BaseHTTPRequestHandler):
    def _send(self, code, body, ctype):
        data = body.encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        if self.path.split("?")[0] not in ("/", "/index.html"):
            return self._send(404, "not found", "text/plain; charset=utf-8")
        payload = json.dumps(page_data(), ensure_ascii=False).replace("</", "<\\/")
        self._send(200, PAGE.replace("__DATA__", payload), "text/html; charset=utf-8")

    def do_POST(self):
        if self.path != "/api/review":
            return self._send(404, "not found", "text/plain; charset=utf-8")
        try:
            body = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0))).decode("utf-8"))
            save([(c["key"], c.get("mark", ""), c.get("reason", "")) for c in body["changes"]])
            self._send(200, json.dumps({"ok": True}), "application/json")
        except Exception as ex:  # noqa: BLE001
            self._send(400, json.dumps({"ok": False, "error": str(ex)}, ensure_ascii=False), "application/json")

    def log_message(self, fmt, *args):
        pass


