MARKS = {"通过", "不通过", ""}
LOCK = threading.Lock()          # one save and regeneration at a time


def read(path):
    return list(csv.DictReader(open(path, encoding="utf-8"))) if path.exists() else []


def row_keys():
    return {f"{r['character']} {r['anim']}" for r in read(v2_actions.OUT_CSV)}


def page_data():
    reviews = v2_actions.reviews()
    rows = []
    for r in read(v2_actions.OUT_CSV):
        key = f"{r['character']} {r['anim']}"
        mark, reason = reviews.get(key, ("", ""))
        rows.append({**r, "key": key, "mark": mark, "reason": reason})
    names = []
    for key, (what, proposal, now) in v2_actions.NAME_REVIEWS.items():
        mark, reason = reviews.get(key, ("", ""))
        names.append({"key": key, "what": what, "proposal": proposal, "now": now, "mark": mark, "reason": reason})
    return {"rows": rows, "names": names, "decided": v2_actions.DECIDED}


def save(changes):
    """changes: [(key, mark, reason)]; writes the review file, then regenerates the table."""
    valid = row_keys() | set(v2_actions.NAME_REVIEWS)
    for key, mark, _ in changes:
        if key not in valid:
            raise ValueError(f"unknown row {key!r}")
        if mark not in MARKS:
            raise ValueError(f"unknown mark {mark!r}")
    with LOCK:
        current = {r["key"]: r for r in read(v2_actions.REVIEW_CSV)}
        now = datetime.now().isoformat(timespec="seconds")
        for key, mark, reason in changes:
            reason = " ".join(str(reason).split())
            if mark or reason:
                current[key] = {"key": key, "mark": mark, "reason": reason, "updated": now}
            else:
                current.pop(key, None)
        buf = io.StringIO()
        w = csv.DictWriter(buf, fieldnames=v2_actions.REVIEW_FIELDS, lineterminator="\r\n")
        w.writeheader()
        w.writerows(sorted(current.values(), key=lambda r: r["key"]))
        tmp = v2_actions.REVIEW_CSV.with_suffix(".tmp")
        tmp.write_text(buf.getvalue(), encoding="utf-8", newline="")
        os.replace(tmp, v2_actions.REVIEW_CSV)
        v2_actions.main()


